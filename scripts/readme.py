"""Write the generated parts from the committed reports: the README results block, the two charts and the
dashboard's data file. Nothing here computes a number; every figure comes from reports/*.json.

    python3 scripts/readme.py
"""

from __future__ import annotations

import json
import re
import tomllib
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LABELS = {
    "backbone": "Backbone (every safeguard on)",
    "first_version": "First-version pipeline (none of them)",
    "without_complete_files_only": "without: load only complete files",
    "without_load_content_once": "without: load a redelivered file once",
    "without_dedupe_click_ids": "without: one row per click id",
    "without_repeat_click_window": "without: the contract's repeat-click window",
    "without_bot_rules": "without: invalid-traffic rules",
    "without_partner_local_time": "without: months in the partner's time zone",
    "without_quarantine_unknown_values": "without: hold values outside the schema contract",
    "without_reprice_amendments": "without: amendments from their effective date",
    "without_fx_as_published": "without: EUR at the rate actually published",
    "without_hold_invoices": "without: hold an invoice while a check fails",
    "without_adjustment_notes": "without: credit and debit notes after issue",
}
INCIDENT = {"outage": "Log shipping stopped", "double_firing": "Every redirect logged twice",
            "bot_storm": "Scraper clicking hotel offers", "enum_drift": "New device value before the schema contract",
            "fx_delay": "Reference rates stopped arriving"}


def load(name: str) -> dict | None:
    p = ROOT / "reports" / name
    return json.loads(p.read_text()) if p.exists() else None


def partner_names() -> dict[str, str]:
    cfg = tomllib.loads((ROOT / "config" / "world.toml").read_text())
    return {p["id"]: p["name"] for p in cfg["partners"]}


def eur(x: float) -> str:
    return f"€{x:,.0f}"


def variant_table(rep: dict) -> str:
    rows = ["| Pipeline | Avoidable error, first issue | Avoidable error, after notes | Invoices avoidably off by more than 0.5% (first issue) | Partner disputes |",
            "|---|---:|---:|---:|---:|"]
    order = sorted(rep["variants"], key=lambda k: (k != "backbone", k != "first_version",
                                                   -rep["variants"][k]["first_issue_avoidable_error_pct"]))
    for k in order:
        v = rep["variants"][k]
        name = f"**{LABELS[k]}**" if k in ("backbone", "first_version") else LABELS[k]
        rows.append(f"| {name} | {v['first_issue_avoidable_error_pct']:.2f}% | {v['final_avoidable_error_pct']:.2f}% | "
                    f"{v['invoices_avoidably_wrong_first_issue']} of {v['invoices']} | {v['partner_disputes']} |")
    return "\n".join(rows)


def incident_table(rep: dict) -> str:
    rows = ["| Planted incident | Where | First check to fail | Hours from start to alert |", "|---|---|---|---:|"]
    for d in rep["variants"]["backbone"]["detection"]:
        rows.append(f"| {INCIDENT[d['incident']]} | {d['where']}, {d['start'][:10]} | "
                    f"{('`' + d['first_check'] + '`') if d['caught'] else 'missed'} | {d['hours_to_alert'] if d['caught'] else '—'} |")
    return "\n".join(rows)


def block(dev: dict, held: dict | None, bench: dict | None) -> str:
    b, f = dev["variants"]["backbone"], dev["variants"]["first_version"]
    bf = b["bot_filter"]
    out = [
        "<!-- results:start (generated by scripts/readme.py from reports/; do not edit) -->",
        "",
        "Two yardsticks. **Avoidable error** is the distance from the best any pipeline could bill from these logs; "
        "**against what was truly owed** also counts the bots that are indistinguishable from people in them.",
        "",
        "| Dev world, 36 partner-months | Backbone | First-version pipeline |",
        "|---|---:|---:|",
        f"| Avoidable billing error when invoices first went out | **{b['first_issue_avoidable_error_pct']:.2f}%** ({eur(b['first_issue_avoidable_error_eur'])}) | {f['first_issue_avoidable_error_pct']:.2f}% ({eur(f['first_issue_avoidable_error_eur'])}) |",
        f"| Invoices avoidably off by more than 0.5% when first issued | **{b['invoices_avoidably_wrong_first_issue']} of {b['invoices']}** | {f['invoices_avoidably_wrong_first_issue']} of {f['invoices']} |",
        f"| Billing error against what was truly owed, after notes | **{b['final_error_pct']:.2f}%** ({eur(b['final_abs_error_eur'])}) | {f['final_error_pct']:.2f}% ({eur(f['final_abs_error_eur'])}) |",
        f"| of which bots indistinguishable from people in the logs | {eur(b['indistinguishable_bot_billing_eur'])} | {eur(f['indistinguishable_bot_billing_eur'])} |",
        f"| Partner disputes (partner's own count more than 2% away) | **{b['partner_disputes']}** | {f['partner_disputes']} |",
        f"| Invoices sent while a blocking check was failing | **{b['issued_with_open_checks']}** | {f['issued_with_open_checks']} |",
        f"| Credit and debit notes issued | {b['adjustment_notes']} | {f['adjustment_notes']} |",
        f"| Latest day of the month an invoice went out | {b['latest_issue_day']} | {f['latest_issue_day']} |",
        f"| EUR revenue mart against the truth | **{b['revenue']['error_pct']:.2f}%** | {f['revenue']['error_pct']:.2f}% |",
        "",
        f"{eur(b['true_billing_eur'])} truly owed over September and October; "
        f"{b['checks_run']:,} check results recorded, {b['alerts']} alerts raised.",
        "",
        "![Avoidable billing error by pipeline](docs/img/safeguards.png)",
        "",
        "**What each safeguard is worth** (the backbone with one switched off, everything else equal):",
        "",
        variant_table(dev),
        "",
        "**Planted incidents** (the pipeline is not told about any of them):",
        "",
        incident_table(dev),
        "",
        f"**Invalid-traffic rules:** {100 * bf['precision']:.2f}% of flagged clicks were really invalid; they caught "
        f"{100 * bf['recall_detectable_bots']:.1f}% of the bots that show a signal in the logs and "
        f"{100 * bf['storm_recall']:.1f}% of the scraper storm, and flagged {bf['people_flagged']} real people. "
        f"{bf['undetectable_bot_clicks']:,} bot clicks came through residential proxies at human pace; nothing in "
        "redirect logs separates them from travellers, so they were billed.",
    ]
    if held:
        hb, hf = held["variants"]["backbone"], held["variants"]["first_version"]
        out += ["", "**Held-out world, first and only run** (another seed, other incidents, "
                "settings frozen before it ran):", "",
                "| | Backbone | First-version pipeline |", "|---|---:|---:|",
                f"| Avoidable billing error when invoices first went out | **{hb['first_issue_avoidable_error_pct']:.2f}%** | {hf['first_issue_avoidable_error_pct']:.2f}% |",
                f"| Invoices avoidably off by more than 0.5% when first issued | **{hb['invoices_avoidably_wrong_first_issue']} of {hb['invoices']}** | {hf['invoices_avoidably_wrong_first_issue']} of {hf['invoices']} |",
                f"| Billing error against what was truly owed, after notes | {hb['final_error_pct']:.2f}% | {hf['final_error_pct']:.2f}% |",
                f"| Partner disputes | **{hb['partner_disputes']}** | {hf['partner_disputes']} |",
                f"| Incidents caught | **{sum(d['caught'] for d in hb['detection'])} of {len(hb['detection'])}** | — |"]
    if bench:
        out += ["", f"**Query rewrites** (on {bench['clicks']:,} clicks, {bench['machine']}; identical rows required):", "",
                "| Query | Before | After | Faster | Same rows |", "|---|---:|---:|---:|---|"]
        for p in bench["pairs"]:
            out.append(f"| {p['query']} | {p['before_s']} s | {p['after_s']} s | {p['speedup']}× | {'yes' if p['identical'] else 'NO'} |")
    out += ["", "<!-- results:end -->"]
    return "\n".join(out)


def charts(dev: dict) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    v = dev["variants"]
    keys = sorted(v, key=lambda k: v[k]["first_issue_avoidable_error_pct"])
    fig, ax = plt.subplots(figsize=(8, 4.6), dpi=110)
    colors = ["#1E7F55" if k == "backbone" else "#B83A2E" if k == "first_version" else "#5A646F" for k in keys]
    vals = [v[k]["first_issue_avoidable_error_pct"] for k in keys]
    ax.barh([LABELS[k] for k in keys], vals, color=colors)
    for i, x in enumerate(vals):
        ax.text(x, i, f"  {x:.2f}%", va="center", fontsize=8)
    ax.set_xlabel("avoidable billing error when invoices first went out, % (dev world, 36 partner-months)")
    ax.spines[["top", "right"]].set_visible(False)
    ax.tick_params(axis="y", labelsize=8)
    fig.tight_layout()
    (ROOT / "docs" / "img").mkdir(parents=True, exist_ok=True)
    fig.savefig(ROOT / "docs" / "img" / "safeguards.png", metadata={"Software": None})
    plt.close(fig)


def dashboard(dev: dict) -> None:
    names = partner_names()
    b, f = dev["variants"]["backbone"], dev["variants"]["first_version"]
    inv = []
    for r in b["invoice_rows"]:
        y, m = map(int, r["month"].split("-"))
        due = datetime(y + (m == 12), m % 12 + 1, 2)
        held = (datetime.fromisoformat(r["issued"][:10]) - due).days if r["issued"] else None
        inv.append({"partner": r["partner"], "name": names[r["partner"]], "month": r["month"], "currency": r["currency"],
                    "issued": r["issued"], "notes": r["notes"],
                    "first_err_pct": round(100 * r["first_avoidable_err_eur"] / r["ref_eur"], 2) if r["issued"] else None,
                    "final_err_pct": round(100 * r["final_avoidable_err_eur"] / r["ref_eur"], 2) if r["issued"] else None,
                    "held_days": held if held is not None else 8})
    variants = [{"key": k, "label": LABELS[k], "final_error_pct": x["first_issue_avoidable_error_pct"],
                 "invoices_wrong_final": x["invoices_wrong_final"], "partner_disputes": x["partner_disputes"]}
                for k, x in sorted(dev["variants"].items(), key=lambda kv: kv[1]["first_issue_avoidable_error_pct"])]
    out = {"world": dev["world"],
           "headline": {"backbone_error_pct": b["first_issue_avoidable_error_pct"],
                        "first_version_error_pct": f["first_issue_avoidable_error_pct"],
                        "true_billing_eur": b["true_billing_eur"], "disputes": [b["partner_disputes"], f["partner_disputes"]]},
           "invoices": inv, "variants": variants, "incidents": b["detection"]}
    p = ROOT / "web" / "public" / "data" / "dashboard.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(out, indent=1) + "\n")


def main() -> None:
    dev = load("dev.json")
    held, bench = load("heldout.json"), load("bench.json")
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = re.sub(r"<!-- results:start.*?<!-- results:end -->", lambda _: block(dev, held, bench), text, flags=re.S)
    readme.write_text(new)
    charts(dev)
    dashboard(dev)
    print("README, docs/img/safeguards.png and web/public/data/dashboard.json written")


if __name__ == "__main__":
    main()
